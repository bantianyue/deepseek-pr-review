import { getOctokit } from "@actions/github";
import { REVIEW_MARKER } from "./constants";

type Octokit = ReturnType<typeof getOctokit>;

export function buildCommentBody(reviewMarkdown: string): string {
  return `${REVIEW_MARKER}
# DeepSeek PR Review

${reviewMarkdown.trim()}

---
<sub>Generated by <a href="https://github.com/bantianyue/deepseek-pr-review">deepseek-pr-review</a> (advisory comment).</sub>`;
}

export async function upsertReviewComment(options: {
  octokit: Octokit;
  owner: string;
  repo: string;
  issueNumber: number;
  body: string;
}): Promise<void> {
  const { octokit, owner, repo, issueNumber, body } = options;
  const comments = await octokit.paginate(octokit.rest.issues.listComments, {
    owner,
    repo,
    issue_number: issueNumber,
    per_page: 100,
  });

  const existing = comments.find((c) => c.body?.includes(REVIEW_MARKER));
  if (existing) {
    await octokit.rest.issues.updateComment({
      owner,
      repo,
      comment_id: existing.id,
      body,
    });
    return;
  }

  await octokit.rest.issues.createComment({
    owner,
    repo,
    issue_number: issueNumber,
    body,
  });
}
